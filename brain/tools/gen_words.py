"""Writes brain/game/gta_words.h: the instruction words of the player's libGTASA.so that the brain relies on.
The mod compares every one of them with the game in memory before it changes anything.

    python3 brain/tools/gen_words.py path/to/libGTASA.so
"""
import struct, sys
from pathlib import Path
from elftools.elf.elffile import ELFFile

# name, address, number of words
FUNCS = [('SCRIPTS_PROCESS', 0x3f3ad8, 4), ('GUNSHOT_CTOR', 0x442854, 4), ('LOS_CLEAR', 0x5075a4, 4), ('DRAW_POLY', 0x6ee4a4, 4), ('CALC_SCREEN', 0x6e9df8, 4),
         ('GET_PED', 0x4f2378, 4), ('FIND_PLAYER_PED', 0x4efae0, 4), ('GET_TASK_USE_GUN', 0x5bcb80, 4), ('IS_ON_MISSION', 0x3f4158, 4), ('HUD_DRAW', 0x51f6f0, 0)]
# single instructions that prove a structure offset (see brain/research/game_facts.md, appendix 2)
ANCHORS = [(0x4f23a0, 'ped pool element 0x9c8'), (0x4f241c, 'vehicle pool element 0xc68'), (0x40fb74, 'ped health +0x6ac'), (0x41d648, 'ped armour +0x6b4'),
           (0x404fa4, 'ped type +0x720'), (0x41c2a0, 'weapon slot +0x8dc'), (0x41c2a8, 'weapon slots +0x730'), (0x3f65dc, 'in-vehicle flag +0x585'),
           (0x3f65ec, 'ped vehicle +0x708'), (0x4113a0, 'firing flag +0x586'), (0x5958c4, 'created-by +0x548'), (0x59afc8, 'ped state +0x54c'),
           (0x5bde98, 'acquaintances +0x63c'), (0x41f3d8, 'last damage entity +0x940'), (0x443e94, 'last damage time +0x948'), (0x41c228, 'driver +0x5a0'),
           (0x40fbb0, 'vehicle health +0x634'), (0x40eef8, 'passenger count +0x5e8'), (0x41bc70, 'vehicle fire +0x5f8'), (0x4f0478, 'player data +0x8'),
           (0x3f69c0, 'wanted stars +0x2c'), (0x4efb14, 'player info size 0x1d8'), (0x5dd8b0, 'use-gun target +0x28'), (0x5e3020, 'kill-ped target +0x20'),
           (0x4efee8, 'matrix pointer +0x18'), (0x4efef0, 'matrix position +0x30'), (0x4f03b4, 'move speed +0x68'), (0x4269a0, 'model index +0x32'),
           (0x5ab86c, 'group members +0x8'), (0x3fcfb0, 'player group +0x4c'),
           (0x50cf18, 'line of sight: page of the GOT entry of pIgnoreEntity'), (0x50cf24, 'line of sight: the GOT entry +0x180'),
           (0x3f1fcc, 'CollectParameters (CLEO reads opcode parameters with it)'), (0x3f2654, 'GetPointerToScriptVariable')]
SLOTS = [('SCRIPTS', 0x845438, 0x3f3ad8), ('HUD', 0x845ec8, 0x51f6f0), ('GUNSHOT', 0x843f10, 0x442854)]


def main(path):
    data = Path(path).read_bytes()
    elf = ELFFile(open(path, 'rb'))
    loads = [s for s in elf.iter_segments() if s['p_type'] == 'PT_LOAD']

    def word(vaddr):
        for s in loads:
            if s['p_vaddr'] <= vaddr < s['p_vaddr'] + s['p_filesz']:
                return struct.unpack_from('<I', data, s['p_offset'] + vaddr - s['p_vaddr'])[0]
        raise SystemExit('address %#x is not in the file' % vaddr)
    out = ['/* Generated by brain/tools/gen_words.py from the player\'s libGTASA.so (%d bytes). Do not edit. */' % len(data), '#ifndef GTA_WORDS_H', '#define GTA_WORDS_H', '']
    for name, addr, n in FUNCS:
        out.append('#define G_%s 0x%xUL' % (name, addr))
    out.append('')
    out.append('struct gta_word { unsigned int at, word; };')
    out.append('static const struct gta_word GTA_WORDS[] = {')
    for name, addr, n in FUNCS:
        for i in range(n):
            out.append('    {0x%x, 0x%08xU},   /* %s + %d */' % (addr + 4 * i, word(addr + 4 * i), name, 4 * i))
    for addr, what in ANCHORS:
        out.append('    {0x%x, 0x%08xU},   /* %s */' % (addr, word(addr), what))
    out.append('};')
    out.append('')
    out.append('/* GOT slots that are swapped, and the function each must point to before the swap */')
    for name, slot, target in SLOTS:
        out.append('#define GOT_%s 0x%xUL' % (name, slot))
        out.append('#define GOT_%s_TARGET 0x%xUL' % (name, target))
    out.append('#endif')
    (Path(__file__).resolve().parent.parent / 'game' / 'gta_words.h').write_text('\n'.join(out) + '\n')
    print('wrote gta_words.h: %d words' % (sum(n for _, _, n in FUNCS) + len(ANCHORS)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
